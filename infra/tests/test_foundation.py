def test_table_keys_index_ttl_and_no_recovery(env):
    name, s = env
    s.foundation.has_resource_properties(
        "AWS::DynamoDB::Table",
        {
            "TableName": f"plan-{name}-sessions",
            "BillingMode": "PAY_PER_REQUEST",
            "KeySchema": [
                {"AttributeName": "session_id", "KeyType": "HASH"},
                {"AttributeName": "sk", "KeyType": "RANGE"},
            ],
            "TimeToLiveSpecification": {"AttributeName": "expires_at", "Enabled": True},
            "PointInTimeRecoverySpecification": {"PointInTimeRecoveryEnabled": False},
            "SSESpecification": {
                "SSEEnabled": True,
                "SSEType": "KMS",
                "KMSMasterKeyId": Match.any_value(),
            },
            "GlobalSecondaryIndexes": [
                {
                    "IndexName": "expiry-index",
                    "KeySchema": [
                        {"AttributeName": "gsi_pk", "KeyType": "HASH"},
                        {"AttributeName": "expires_at", "KeyType": "RANGE"},
                    ],
                    "Projection": {"ProjectionType": "KEYS_ONLY"},
                }
            ],
        },
    )
    s.foundation.resource_count_is("AWS::DynamoDB::Table", 1)
    table = next(iter(s.foundation.find_resources("AWS::DynamoDB::Table").values()))
    assert "StreamSpecification" not in table["Properties"]
    attrs = table["Properties"]["AttributeDefinitions"]
    types = {a["AttributeName"]: a["AttributeType"] for a in attrs}
    assert types == {"session_id": "S", "sk": "S", "gsi_pk": "S", "expires_at": "N"}


