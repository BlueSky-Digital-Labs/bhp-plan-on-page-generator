def test_key_lets_cloudwatch_logs_write_only_for_this_environments_groups(env):
    name, s = env
    key = next(iter(s.foundation.find_resources("AWS::KMS::Key").values()))
    logs = [
        st
        for st in key["Properties"]["KeyPolicy"]["Statement"]
        if st.get("Principal") == {"Service": "logs.ap-southeast-2.amazonaws.com"}
    ]
    assert len(logs) == 1
    assert f"log-group:/plan/{name}/*" in json.dumps(logs[0]["Condition"])


def test_secrets_names_and_values(env):
    name, s = env
    secrets = {
        r["Properties"]["Name"]: r["Properties"]
        for r in s.foundation.find_resources("AWS::SecretsManager::Secret").values()
    }
    assert set(secrets) == {f"plan-{name}/access-code-hash", f"plan-{name}/cookie-signing-key"}

    placeholder = secrets[f"plan-{name}/access-code-hash"]["SecretString"]
    assert not placeholder.startswith("$argon2")  # the app must fail closed until it is replaced

    cookie = secrets[f"plan-{name}/cookie-signing-key"]
    assert "SecretString" not in cookie  # generated by Secrets Manager, never in the template
    gen = cookie["GenerateSecretString"]
    assert gen["PasswordLength"] >= 48 and gen["ExcludePunctuation"] is True
    assert "GenerateStringKey" not in gen and "SecretStringTemplate" not in gen  # plain string
    for props in secrets.values():
        assert "KmsKeyId" in props


def test_no_secret_material_in_any_output_or_template(env):
    _, s = env
    for template in (s.foundation, s.service):
        assert "resolve:secretsmanager" not in json.dumps(j(template))
        for out in j(template).get("Outputs", {}).values():
            text = json.dumps(out)
            assert "SecretString" not in text and "NOT-SET" not in text
            assert "SecretValue" not in text and "GetSecretValue" not in text
    # The placeholder lives in the access-code secret and nowhere else.
    assert json.dumps(j(s.service)).count("NOT-SET") == 0
    assert json.dumps(j(s.foundation)).count("NOT-SET") == 1


