#!/usr/bin/env bash
# Set the shared access code for an environment.
#
#   AWS_PROFILE=<profile> scripts/set-access-secrets.sh <test|prod> [region]
#
# Prompts for the code with hidden input, hashes it with Argon2 (the same library the app
# verifies with) and stores only the hash in plan-<env>/access-code-hash. The code is never
# echoed, never put on a command line, never written to a file, and not kept in history. Uses
# whatever AWS credentials your shell already has; needs secretsmanager:PutSecretValue on the
# secret and kms:GenerateDataKey/kms:Decrypt on the environment's key.
#
# The cookie signing key is generated by CloudFormation and is not set here. To rotate it see
# docs/deployment.md.
set -euo pipefail
umask 077

env_name=${1:?usage: set-access-secrets.sh <test|prod> [region]}
case "$env_name" in test | prod) ;; *) echo "environment must be test or prod" >&2; exit 2 ;; esac
region=${2:-${AWS_REGION:-ap-southeast-2}}
secret_id="plan-${env_name}/access-code-hash"
root=$(cd "$(dirname "$0")/.." && pwd)

read -r -s -p "New access code for ${env_name}: " code
echo >&2
read -r -s -p "Repeat it: " again
echo >&2
if [ -z "$code" ] || [ "$code" != "$again" ]; then
  echo "Empty, or the two entries differ. Nothing changed." >&2
  exit 1
fi
if [ "${#code}" -gt 128 ]; then # the app refuses anything longer at the entry page
  echo "The app accepts at most 128 characters. Nothing changed." >&2
  exit 1
fi
unset again

# printf is a shell builtin, so the code is not visible in the process list.
hash=$(printf '%s' "$code" | uv run --quiet --frozen --no-dev --project "$root/backend" python -c \
  "import sys; from argon2 import PasswordHasher; sys.stdout.write(PasswordHasher().hash(sys.stdin.read()))")
unset code
# shellcheck disable=SC2016 # the dollar sign is literal
case "$hash" in '$argon2'*) ;; *) echo "Hashing failed. Nothing changed." >&2; exit 1 ;; esac

# The hash goes in through stdin, not the command line. VersionId is not secret.
printf '%s' "$hash" | aws secretsmanager put-secret-value --region "$region" \
  --secret-id "$secret_id" --secret-string file:///dev/stdin \
  --query VersionId --output text > /dev/null
unset hash
echo "Updated ${secret_id} in ${region}. The next entry attempt uses it (no restart needed)." >&2
